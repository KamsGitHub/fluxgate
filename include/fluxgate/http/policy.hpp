#pragma once

#include <cstdint>
#include <string>
#include <string_view>

#include "fluxgate/http/message.hpp"

namespace fluxgate::http {

// Decides whether a syntactically valid request may be proxied. Returns 0 if so,
// otherwise the status code to reject it with. Everything not explicitly supported
// is refused here, before any upstream is contacted.
[[nodiscard]] int validate_request(const MessageHead& request, std::uint64_t max_body_bytes);

// True if the client is waiting for "100 Continue" before sending its body.
[[nodiscard]] bool expects_continue(const MessageHead& request) noexcept;

// Serialises the request for the upstream: hop-by-hop headers and client-supplied
// forwarding headers are removed, and FluxGate's own are appended.
[[nodiscard]] std::string render_upstream_request(const MessageHead& request,
                                                  std::string_view client_ip);

// Serialises an upstream response head for the client. Body bytes are relayed
// untouched, so Transfer-Encoding and Trailer are kept to keep describing them.
[[nodiscard]] std::string render_client_response(const MessageHead& response);

// As above, for a 1xx response, which never carries Connection: close.
[[nodiscard]] std::string render_interim_response(const MessageHead& response);

// A complete response generated by the proxy itself. `omit_body` is for HEAD.
[[nodiscard]] std::string render_error_response(int status, bool omit_body);

[[nodiscard]] std::string_view status_reason(int status) noexcept;

// The target without its query string, which often holds tokens and must not be
// logged.
[[nodiscard]] std::string_view target_path(std::string_view target) noexcept;

}  // namespace fluxgate::http
